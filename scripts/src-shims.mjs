// Source-path shims for packaged extensions (Kurahi 2.2). Used by scripts/bundle.mjs (lib/) and
// scripts/npm-pack.mjs (package/): both ship dist/, not src/, yet extensions import core modules
// by repository path. See docs/security/enterprise-profile.md.
import fs from "node:fs";
import path from "node:path";
import ts from "typescript";
import { unresolvedImports } from "./enterprise-check.mjs";

/**
 * Extensions import core modules by repository path (`../../src/x.js`), which resolves in a
 * checkout but not in a package: it has dist/, not src/. For every such import, write
 * <pkg>/src/x.js re-exporting <pkg>/dist/x.js, so the plugin loads the built core module. Only
 * imported modules get a shim. Returns the count and the static imports that have no built
 * module (the caller fails on those).
 */
export function writeSrcShims(lib, extensions) {
  const srcDir = path.join(lib, "src");
  const distDir = path.join(lib, "dist");
  let written = 0;
  const missing = [];
  for (const m of unresolvedImports(lib, extensions)) {
    const rel = path.relative(srcDir, m.target);
    const built = path.join(distDir, rel.replace(/\.ts$/, ".js"));
    if (rel.startsWith("..") || path.isAbsolute(rel) || !fs.existsSync(built)) {
      // A dynamic import may be a guarded fallback (llm-task tries src/ first, then a built path).
      if (!m.dynamic) {
        missing.push(m);
      }
      continue;
    }
    const shim = path.join(srcDir, rel.replace(/\.ts$/, ".js"));
    if (fs.existsSync(shim)) {
      continue;
    }
    const spec = path.relative(path.dirname(shim), built).split(path.sep).join("/");
    const hasDefault = hasDefaultExport(fs.readFileSync(built, "utf8"));
    fs.mkdirSync(path.dirname(shim), { recursive: true });
    fs.writeFileSync(
      shim,
      `// Generated by scripts/src-shims.mjs: extensions import core modules by source path.\n` +
        `export * from "${spec}";\n` +
        (hasDefault ? `export { default } from "${spec}";\n` : ""),
    );
    written++;
  }
  return { written, missing };
}

/**
 * Whether an ES module exports `default`, read from its syntax tree: a text match also hits
 * strings and comments (agent-scope.js logs "... as default"), and a shim that re-exports a
 * missing default fails to link, so the extension does not load.
 */
export function hasDefaultExport(code) {
  const file = ts.createSourceFile("m.js", code, ts.ScriptTarget.Latest, false, ts.ScriptKind.JS);
  return file.statements.some((st) => {
    if (ts.isExportAssignment(st)) {
      return true;
    }
    if (ts.isExportDeclaration(st)) {
      const clause = st.exportClause;
      if (clause === undefined) {
        return false;
      }
      if (ts.isNamespaceExport(clause)) {
        return clause.name.text === "default";
      }
      return clause.elements.some((el) => el.name.text === "default");
    }
    const mods = ts.canHaveModifiers(st) ? ts.getModifiers(st) : undefined;
    return (
      mods?.some((m) => m.kind === ts.SyntaxKind.ExportKeyword) === true &&
      mods.some((m) => m.kind === ts.SyntaxKind.DefaultKeyword)
    );
  });
}
