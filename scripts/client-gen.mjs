#!/usr/bin/env node
// Generates the typed @kodasoken/kurahi-client sources from openapi/kolo-gateway.openapi.json (M4b).
//   node scripts/client-gen.mjs            write packages/client/src/generated/*
//   node scripts/client-gen.mjs --check    fail when the committed files differ (drift check)
//
// No network and no external generator: a small JSON-Schema -> TypeScript mapper for the subset
// the gateway spec uses ($ref, const, enum, anyOf/oneOf/allOf, type (incl. arrays of types),
// properties/required, additionalProperties, patternProperties, items/prefixItems).
// Output is a pure function of the spec, so two runs produce byte-identical files.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const SPEC_PATH = path.join(ROOT, "openapi", "kolo-gateway.openapi.json");
export const GENERATED_DIR = path.join(ROOT, "packages", "client", "src", "generated");

const HEADER =
  "// GENERATED by scripts/client-gen.mjs from openapi/kolo-gateway.openapi.json. Do not edit.\n" +
  "// Regenerate with `pnpm client:gen`; `pnpm client:check` fails when this file drifts.\n" +
  "// SPDX-License-Identifier: MIT\n";

const HTTP_METHODS = ["get", "put", "post", "delete", "patch", "head", "options"];
const IDENT = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

export function pascal(id) {
  const words = String(id)
    .replace(/[^A-Za-z0-9]+/g, " ")
    .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
    .trim()
    .split(/\s+/)
    .filter(Boolean);
  const out = words.map((w) => w[0].toUpperCase() + w.slice(1)).join("");
  return /^[0-9]/.test(out) ? `_${out}` : out;
}

function propKey(name) {
  return IDENT.test(name) ? name : JSON.stringify(name);
}

function docComment(text, indent) {
  if (typeof text !== "string" || !text.trim()) {
    return "";
  }
  const lines = text.replace(/\*\//g, "*\\/").trim().split(/\r?\n/);
  if (lines.length === 1) {
    return `${indent}/** ${lines[0]} */\n`;
  }
  return `${indent}/**\n${lines.map((l) => `${indent} * ${l}`.trimEnd()).join("\n")}\n${indent} */\n`;
}

// Prefix for $ref type names: "" inside types.ts, "T." in files that `import type * as T`.
let refPrefix = "";

function withRefPrefix(prefix, fn) {
  const prev = refPrefix;
  refPrefix = prefix;
  try {
    return fn();
  } finally {
    refPrefix = prev;
  }
}

function refName(ref) {
  const m = /^#\/components\/schemas\/(.+)$/.exec(ref);
  if (!m) {
    throw new Error(`client-gen: unsupported $ref ${ref}`);
  }
  return refPrefix + pascal(m[1]);
}

/**
 * @param {string[]} parts
 * @returns {string}
 */
function union(parts) {
  const uniq = [...new Set(parts)];
  if (uniq.length === 0) {
    return "never";
  }
  if (uniq.includes("unknown")) {
    return "unknown";
  }
  return uniq.length === 1 ? uniq[0] : uniq.map((p) => (needsParens(p) ? `(${p})` : p)).join(" | ");
}

/**
 * @param {string} t
 * @returns {boolean}
 */
function needsParens(t) {
  // Object literals, arrays and generics are self-delimiting; bare unions/intersections are not.
  // Only operators at nesting depth 0 count: `{ a: 1 } | { b: 2 }` starts with "{" but is a union.
  return hasTopLevelOperator(t);
}

/**
 * @param {string} t
 * @returns {boolean}
 */
function hasTopLevelOperator(t) {
  let depth = 0;
  let quote = "";
  for (let i = 0; i < t.length; i++) {
    const c = t[i];
    if (quote) {
      if (c === "\\") {
        i++;
      } else if (c === quote) {
        quote = "";
      }
    } else if (c === '"' || c === "'") {
      quote = c;
    } else if (c === "{" || c === "(" || c === "[" || c === "<") {
      depth++;
    } else if (c === "}" || c === ")" || c === "]" || c === ">") {
      depth--;
    } else if (depth === 0 && (c === "|" || c === "&") && t[i - 1] === " " && t[i + 1] === " ") {
      return true;
    }
  }
  return false;
}

/** Map one JSON Schema to a TypeScript type expression. */
export function schemaToTs(schema, indent = "") {
  if (schema === true || schema === undefined) {
    return "unknown";
  }
  if (schema === false) {
    return "never";
  }
  if (typeof schema !== "object" || schema === null) {
    return "unknown";
  }
  if (typeof schema.$ref === "string") {
    return refName(schema.$ref);
  }
  if ("const" in schema) {
    return JSON.stringify(schema.const);
  }
  if (Array.isArray(schema.enum)) {
    return union(schema.enum.map((v) => JSON.stringify(v)));
  }
  if (Array.isArray(schema.anyOf) || Array.isArray(schema.oneOf)) {
    return union((schema.anyOf ?? schema.oneOf).map((s) => schemaToTs(s, indent)));
  }
  if (Array.isArray(schema.allOf)) {
    const parts = schema.allOf.map((s) => schemaToTs(s, indent));
    return parts.length === 1
      ? parts[0]
      : parts.map((p) => (needsParens(p) ? `(${p})` : p)).join(" & ");
  }
  const type = schema.type;
  if (Array.isArray(type)) {
    return union(type.map((t) => schemaToTs({ ...schema, type: t }, indent)));
  }
  switch (type) {
    case "string":
      return "string";
    case "number":
    case "integer":
      return "number";
    case "boolean":
      return "boolean";
    case "null":
      return "null";
    case "array":
      return arrayToTs(schema, indent);
    case "object":
      return objectToTs(schema, indent);
    default:
      if (schema.properties || schema.additionalProperties || schema.patternProperties) {
        return objectToTs(schema, indent);
      }
      if (schema.items || schema.prefixItems) {
        return arrayToTs(schema, indent);
      }
      return "unknown";
  }
}

function arrayToTs(schema, indent) {
  if (Array.isArray(schema.prefixItems)) {
    const items = schema.prefixItems.map((s) => schemaToTs(s, indent));
    const rest =
      schema.items === false ? "" : `, ...${wrapArrayElem(schemaToTs(schema.items, indent))}[]`;
    return `[${items.join(", ")}${rest}]`;
  }
  return `${wrapArrayElem(schemaToTs(schema.items, indent))}[]`;
}

function wrapArrayElem(t) {
  return hasTopLevelOperator(t) ? `(${t})` : t;
}

function objectToTs(schema, indent) {
  const props = schema.properties ?? {};
  const required = new Set(Array.isArray(schema.required) ? schema.required : []);
  const names = Object.keys(props);
  const extra = [];
  if (schema.patternProperties && typeof schema.patternProperties === "object") {
    extra.push(...Object.values(schema.patternProperties).map((s) => schemaToTs(s, `${indent}  `)));
  }
  const ap = schema.additionalProperties;
  if (ap === true) {
    extra.push("unknown");
  } else if (ap && typeof ap === "object") {
    extra.push(schemaToTs(ap, `${indent}  `));
  }
  if (names.length === 0) {
    if (extra.length === 0) {
      return ap === false ? "Record<string, never>" : "Record<string, unknown>";
    }
    return `Record<string, ${union(extra)}>`;
  }
  const inner = `${indent}  `;
  let out = "{\n";
  for (const name of names) {
    const ps = props[name];
    out += docComment(ps && typeof ps === "object" ? ps.description : undefined, inner);
    out += `${inner}${propKey(name)}${required.has(name) ? "" : "?"}: ${schemaToTs(ps, inner)};\n`;
  }
  if (extra.length > 0) {
    // An index signature must admit every declared property type, hence unknown.
    out += `${inner}[key: string]: unknown;\n`;
  }
  return `${out}${indent}}`;
}

function sortedEntries(obj) {
  return Object.entries(obj ?? {}).toSorted(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
}

/** Collect operations in a stable order (path, then HTTP method order). */
export function collectOperations(spec) {
  const ops = [];
  for (const [p, item] of sortedEntries(spec.paths)) {
    for (const method of HTTP_METHODS) {
      const op = item[method];
      if (!op) {
        continue;
      }
      if (typeof op.operationId !== "string" || !IDENT.test(op.operationId)) {
        throw new Error(`client-gen: ${method.toUpperCase()} ${p} has no usable operationId`);
      }
      ops.push({ method: method.toUpperCase(), path: p, op });
    }
  }
  const seen = new Set();
  for (const { op } of ops) {
    if (seen.has(op.operationId)) {
      throw new Error(`client-gen: duplicate operationId ${op.operationId}`);
    }
    seen.add(op.operationId);
  }
  return ops;
}

function resolveResponse(spec, res) {
  if (res && typeof res.$ref === "string") {
    const m = /^#\/components\/responses\/(.+)$/.exec(res.$ref);
    return m ? spec.components?.responses?.[m[1]] : undefined;
  }
  return res;
}

function contentKind(contentType) {
  const ct = contentType.toLowerCase();
  if (ct.includes("json")) {
    return "json";
  }
  if (ct.startsWith("text/")) {
    return "text";
  }
  return "binary";
}

function responseTypes(spec, op, wantSuccess) {
  const types = [];
  for (const [code, raw] of sortedEntries(op.responses)) {
    const ok = /^2\d\d$/.test(code);
    if (ok !== wantSuccess) {
      continue;
    }
    const res = resolveResponse(spec, raw);
    const content = res?.content ?? {};
    const keys = Object.keys(content);
    if (keys.length === 0) {
      types.push("undefined");
      continue;
    }
    for (const ct of keys) {
      const kind = contentKind(ct);
      types.push(
        kind === "json"
          ? schemaToTs(content[ct].schema)
          : kind === "text"
            ? "string"
            : "ArrayBuffer",
      );
    }
  }
  return types;
}

function opParams(op) {
  return (op.parameters ?? []).map((p) => ({
    name: p.name,
    in: p.in,
    required: p.in === "path" ? true : p.required === true,
    schema: p.schema,
    description: p.description,
  }));
}

function bodyInfo(op) {
  const rb = op.requestBody;
  if (!rb) {
    return null;
  }
  const keys = Object.keys(rb.content ?? {});
  const ct = keys.find((k) => k.includes("json")) ?? keys[0];
  if (!ct) {
    return null;
  }
  return { contentType: ct, required: rb.required === true, schema: rb.content[ct].schema };
}

function securityOf(spec, op) {
  const sec = op.security ?? spec.security ?? [];
  return sec.map((req) => Object.keys(req).toSorted());
}

function successKind(spec, op) {
  const kinds = new Set();
  for (const [code, raw] of sortedEntries(op.responses)) {
    if (!/^2\d\d$/.test(code)) {
      continue;
    }
    const res = resolveResponse(spec, raw);
    for (const ct of Object.keys(res?.content ?? {})) {
      kinds.add(contentKind(ct));
    }
  }
  if (kinds.size === 1) {
    return [...kinds][0];
  }
  return kinds.has("json") ? "json" : kinds.has("text") ? "text" : "json";
}

function renderTypes(spec, ops) {
  let out = `${HEADER}/* eslint-disable */\n\n`;
  out += "// ---- component schemas ----\n\n";
  const names = new Set();
  for (const [name, schema] of sortedEntries(spec.components?.schemas)) {
    const tsName = pascal(name);
    if (names.has(tsName)) {
      throw new Error(`client-gen: schema name collision ${tsName}`);
    }
    names.add(tsName);
    out += docComment(schema?.description, "");
    out += `export type ${tsName} = ${schemaToTs(schema)};\n\n`;
  }
  out += "// ---- operations ----\n";
  for (const { method, path: p, op } of ops) {
    const base = pascal(op.operationId);
    for (const suffix of ["Params", "Body", "Response", "ErrorBody"]) {
      if (names.has(base + suffix)) {
        throw new Error(`client-gen: operation type ${base + suffix} collides with a schema`);
      }
      names.add(base + suffix);
    }
    out += `\n// ${op.operationId}: ${method} ${p}\n`;
    const params = opParams(op);
    if (params.length > 0) {
      out += `export type ${base}Params = {\n`;
      for (const prm of params) {
        out += docComment(prm.description ?? `${prm.in} parameter`, "  ");
        out += `  ${propKey(prm.name)}${prm.required ? "" : "?"}: ${schemaToTs(prm.schema, "  ")};\n`;
      }
      out += "};\n";
    } else {
      out += `export type ${base}Params = Record<string, never>;\n`;
    }
    const body = bodyInfo(op);
    out += `export type ${base}Body = ${body ? schemaToTs(body.schema) : "never"};\n`;
    out += `export type ${base}Response = ${union(responseTypes(spec, op, true))};\n`;
    const errs = responseTypes(spec, op, false).filter((t) => t !== "undefined");
    out += `export type ${base}ErrorBody = ${errs.length ? union(errs) : "unknown"};\n`;
  }
  return out;
}

function renderOperations(spec, ops) {
  let out = HEADER;
  out += 'import type { OperationSpec } from "../operation-spec.js";\n';
  out += 'import type * as T from "./types.js";\n\n';
  out += `/** info.version of the spec this client was generated from. */\n`;
  out += `export const SPEC_VERSION = ${JSON.stringify(spec.info?.version ?? "")};\n`;
  out += `/** OpenAPI version of the source document. */\n`;
  out += `export const OPENAPI_VERSION = ${JSON.stringify(spec.openapi ?? "")};\n`;
  const port = spec.servers?.[0]?.variables?.port?.default;
  out += `/** Default gateway port (servers[0].variables.port.default). */\n`;
  out += `export const DEFAULT_PORT = ${Number.parseInt(String(port ?? "18789"), 10)};\n\n`;
  out += "export const operations = {\n";
  for (const { method, path: p, op } of ops) {
    const body = bodyInfo(op);
    const entry = {
      operationId: op.operationId,
      method,
      path: p,
      summary: op.summary ?? "",
      tags: op.tags ?? [],
      security: securityOf(spec, op),
      params: opParams(op).map(({ name, in: where, required }) => ({ name, in: where, required })),
      body: body ? { contentType: body.contentType, required: body.required } : null,
      response: successKind(spec, op),
    };
    out += `  ${op.operationId}: ${JSON.stringify(entry)},\n`;
  }
  out += "} as const satisfies Record<string, OperationSpec>;\n\n";
  out += "export type OperationId = keyof typeof operations;\n\n";
  out += "/** Params, body and response types per operation. */\n";
  out += "export interface OperationTypes {\n";
  for (const { op } of ops) {
    const b = pascal(op.operationId);
    out += `  ${op.operationId}: {\n    params: T.${b}Params;\n    body: T.${b}Body;\n    response: T.${b}Response;\n    error: T.${b}ErrorBody;\n  };\n`;
  }
  out += "}\n";
  return out;
}

function methodDoc(method, p, op) {
  const lines = [`${method} ${p}${op.summary ? ` — ${op.summary}` : ""}`];
  const sec = (op.security ?? []).map((r) => Object.keys(r).join("+")).filter(Boolean);
  lines.push(sec.length ? `Auth: ${sec.join(" | ")}.` : "Auth: none.");
  return docComment(lines.join("\n"), "  ");
}

function renderClient(_spec, ops) {
  let out = HEADER;
  out += 'import { KoloClientBase, type RequestOptions } from "../base.js";\n';
  out += 'import type * as T from "./types.js";\n\n';
  out +=
    "/** Typed client for the Kurahi gateway HTTP API: one method per OpenAPI operationId. */\n";
  out += "export class KoloClient extends KoloClientBase {\n";
  let first = true;
  for (const { method, path: p, op } of ops) {
    const id = op.operationId;
    const b = pascal(id);
    const params = opParams(op);
    const body = bodyInfo(op);
    const paramsRequired = params.some((x) => x.required);
    const args = [];
    if (body) {
      args.push(`body${body.required ? "" : "?"}: T.${b}Body`);
    }
    if (params.length > 0) {
      args.push(`params${paramsRequired ? "" : "?"}: T.${b}Params`);
    }
    args.push("options?: RequestOptions");
    const input = [params.length ? "params" : "", body ? "body" : ""].filter(Boolean).join(", ");
    if (!first) {
      out += "\n";
    }
    first = false;
    out += methodDoc(method, p, op);
    out += `  ${id}(${args.join(", ")}): Promise<T.${b}Response> {\n`;
    out += `    return this.request(${JSON.stringify(id)}, { ${input ? `${input}, ` : ""}...options });\n`;
    out += "  }\n";
  }
  out += "}\n";
  return out;
}

function renderWebsocket(spec) {
  const ws = spec["x-kolo-websocket"];
  if (!ws || !Array.isArray(ws.methods) || !Array.isArray(ws.events)) {
    throw new Error("client-gen: spec has no x-kolo-websocket methods/events");
  }
  const methods = ws.methods.toSorted((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
  const events = ws.events.toSorted((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
  let out = HEADER;
  out += 'import type * as T from "./types.js";\n\n';
  out += `/** WebSocket protocol version (x-kolo-websocket.protocolVersion). */\n`;
  out += `export const WS_PROTOCOL_VERSION = ${Number(ws.protocolVersion ?? 0)};\n`;
  out += `/** The handshake method; it is not callable through call(). */\n`;
  out += `export const WS_HANDSHAKE_METHOD = ${JSON.stringify(ws.handshake?.method ?? "connect")};\n\n`;
  out += `export const wsMethods = ${JSON.stringify(methods.map((m) => m.name))} as const;\n\n`;
  out += `export const wsEvents = ${JSON.stringify(events.map((e) => e.name))} as const;\n\n`;
  out += "export type WsMethod = (typeof wsMethods)[number];\n";
  out += "export type WsEvent = (typeof wsEvents)[number];\n\n";
  out +=
    "/** Params and result per WebSocket method (unknown where the spec gives no schema). */\n";
  out += "export interface WsMethodMap {\n";
  for (const m of methods) {
    const params = m.params ? schemaToTs(m.params, "    ") : "unknown";
    const result = m.result ? schemaToTs(m.result, "    ") : "unknown";
    out += `  ${JSON.stringify(m.name)}: {\n    params: ${params};\n    result: ${result};\n  };\n`;
  }
  out += "}\n\n";
  out += "/** Payload per server event. */\n";
  out += "export interface WsEventMap {\n";
  for (const e of events) {
    out += `  ${JSON.stringify(e.name)}: ${e.payload ? schemaToTs(e.payload, "  ") : "unknown"};\n`;
  }
  out += "}\n\n";
  out += "export type WsHandshakeParams = T.ConnectParams;\n";
  out += "export type WsHelloOk = T.HelloOk;\n";
  out += "export type WsErrorShape = T.ErrorShape;\n";
  return out;
}

/** Render every generated file: { "<file name>": contents }. */
export function renderClientFiles(spec = JSON.parse(fs.readFileSync(SPEC_PATH, "utf8"))) {
  const ops = collectOperations(spec);
  return {
    "types.ts": renderTypes(spec, ops),
    "operations.ts": renderOperations(spec, ops),
    "client.ts": renderClient(spec, ops),
    "websocket.ts": withRefPrefix("T.", () => renderWebsocket(spec)),
  };
}

/** Compare rendered files with the ones on disk. Returns a list of drift messages. */
export function diffClientFiles(files, dir = GENERATED_DIR) {
  const problems = [];
  for (const [name, fresh] of Object.entries(files)) {
    const file = path.join(dir, name);
    const committed = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
    if (committed === null) {
      problems.push(`${name}: missing`);
      continue;
    }
    if (committed !== fresh) {
      const a = committed.split("\n");
      const b = fresh.split("\n");
      let line = 0;
      while (line < Math.max(a.length, b.length) && a[line] === b[line]) {
        line++;
      }
      problems.push(
        `${name}: differs at line ${line + 1}\n  committed: ${(a[line] ?? "<eof>").slice(0, 160)}\n  generated: ${(b[line] ?? "<eof>").slice(0, 160)}`,
      );
    }
  }
  if (fs.existsSync(dir)) {
    for (const name of fs.readdirSync(dir).toSorted()) {
      if (!(name in files)) {
        problems.push(`${name}: not produced by the generator (remove it)`);
      }
    }
  }
  return problems;
}

function main(argv) {
  const files = renderClientFiles();
  if (argv.includes("--check")) {
    const problems = diffClientFiles(files);
    if (problems.length > 0) {
      console.error(
        `client drift: packages/client/src/generated differs from the OpenAPI spec\n${problems.join("\n")}\n` +
          "Run `pnpm client:gen` and commit the result.",
      );
      process.exitCode = 1;
      return;
    }
    console.log(`client: ${Object.keys(files).length} generated files match the OpenAPI spec`);
    return;
  }
  fs.mkdirSync(GENERATED_DIR, { recursive: true });
  for (const [name, body] of Object.entries(files)) {
    fs.writeFileSync(path.join(GENERATED_DIR, name), body);
  }
  const ops = (files["client.ts"].match(/^ {2}[a-zA-Z]+\(/gm) ?? []).length;
  console.log(
    `wrote ${path.relative(ROOT, GENERATED_DIR)}/{${Object.keys(files).join(",")}} (${ops} operations)`,
  );
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main(process.argv.slice(2));
}
